--[[
* XIUI Ability Recast ID Table
* Maps ability NAME (lowercase) -> shared recast/timer ID, sourced from
* Windower's resources_data/job_abilities.lua (recast_id field), extracted
* directly from the game's resource data.
*
* This is keyed by NAME rather than ability ID on purpose: some servers
* renumber ability IDs (e.g. to make room for custom content), so a table
* keyed by ID silently stops matching anything on those servers. Ability
* NAMES don't change between servers, only IDs do, so this stays correct
* regardless of what numeric ID a given server assigns.
*
* This table exists because many abilities SHARE one recast timer with
* other, differently-named abilities (e.g. all DNC Steps share timer 220,
* all Flourish I abilities share timer 221, Sic/Ready are on separate BST
* timers despite looking related, etc). Ashita's GetAbilityByTimerId(id)
* can only resolve ONE canonical ability per timer, so reverse-lookup
* (timer -> ability -> compare name/Id) silently fails for every ability
* that isn't the canonical one Ashita picks for that timer. Resolving a
* known ability's name straight to its recast ID sidesteps that problem.
*
* Entries with recast_id = 0 (job 2-hour abilities, or abilities with no
* shared timer) are intentionally omitted - the caller's fallback path
* already handles those correctly (2hr abilities all share the game's
* dedicated "slot 0").
]]--

